/**
 * Generate discovery + reference docs from the MCP catalog.
 *
 * Single source of truth: src/mcp-server/provider-info.js (providers + methods)
 * and src/mcp-server/schemas.js (per-method input schemas). Run with `npm run docs`.
 *
 * Emits:
 *   - docs/api-reference.md  — grouped provider/method reference
 *   - llms.txt               — compact index for AI tools (llms.txt convention)
 *   - llms-full.txt          — full reference inline for AI tools
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import PROVIDER_INFO from '../src/mcp-server/provider-info.js';
import SCHEMAS from '../src/mcp-server/schemas.js';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const REPO = 'https://github.com/Demon-radio/Bemora.lol';

const CATEGORY_ORDER = [
  'weather', 'geo', 'science', 'health', 'finance', 'government', 'news',
  'research', 'developer', 'social', 'media', 'entertainment', 'sports',
  'travel', 'food', 'language', 'nature', 'religion', 'business', 'ai',
  'utility', 'meta',
];

const providers = Object.entries(PROVIDER_INFO);
const totals = {
  providers: providers.length,
  methods: providers.reduce((n, [, info]) => n + Object.keys(info.methods).length, 0),
  keyless: providers.filter(([, info]) => !info.requiresKey).length,
};

/** Format a method's input schema as `a*, b:number` (`*` = required). */
function fmtParams(schema) {
  if (!schema || !schema.properties || Object.keys(schema.properties).length === 0) return '—';
  const req = new Set(schema.required || []);
  return Object.entries(schema.properties)
    .map(([k, v]) => {
      const t = v.type || 'any';
      return `${k}${req.has(k) ? '*' : ''}:${t}`;
    })
    .join(', ');
}

/** Build a placeholder call-argument object from a schema's required params. */
function exampleArgs(schema) {
  const req = schema?.required || [];
  if (!req.length) return '{}';
  const props = schema.properties || {};
  const parts = req.map((k) => {
    const t = props[k]?.type;
    const val = t === 'number' ? '0' : t === 'boolean' ? 'true' : t === 'array' ? '[]' : "'…'";
    return `${k}: ${val}`;
  });
  return `{ ${parts.join(', ')} }`;
}

function paramDetails(schema) {
  if (!schema || !schema.properties) return [];
  const req = new Set(schema.required || []);
  return Object.entries(schema.properties).map(([k, v]) => {
    const bits = [`\`${k}\``];
    if (req.has(k)) bits.push('(required)');
    bits.push(`— ${v.type || 'any'}`);
    if (v.description) bits.push(`— ${v.description}`);
    return `    - ${bits.join(' ')}`;
  });
}

function byCategory() {
  const groups = new Map();
  for (const [name, info] of providers) {
    const cat = info.category || 'other';
    if (!groups.has(cat)) groups.set(cat, []);
    groups.get(cat).push([name, info]);
  }
  const cats = [...groups.keys()].sort((a, b) => {
    const ia = CATEGORY_ORDER.indexOf(a);
    const ib = CATEGORY_ORDER.indexOf(b);
    if (ia === -1 && ib === -1) return a.localeCompare(b);
    if (ia === -1) return 1;
    if (ib === -1) return -1;
    return ia - ib;
  });
  return cats.map((c) => [c, groups.get(c).sort((a, b) => a[0].localeCompare(b[0]))]);
}

function keyNote(info) {
  if (!info.requiresKey) return 'no key';
  const key = info.keyName || 'API key';
  return `requires \`${key}\``;
}

// ── docs/api-reference.md ────────────────────────────────────────────────────
function renderApiReference() {
  const lines = [
    '# API reference',
    '',
    `> Auto-generated by \`scripts/generate-docs.js\` from \`src/mcp-server/provider-info.js\` and \`src/mcp-server/schemas.js\` (npm run docs). Do not edit by hand.`,
    `> bemora v${pkg.version} · ${totals.providers} providers · ${totals.methods} methods · ${totals.keyless} keyless.`,
    '',
    '## Construction / lifecycle',
    '',
    '- `new Bemora(keys, options)` · `withTenant(id, keys)` / `forTenant(id, keys)` · `setKey(name, value)` / `keys.rotate(name, value)` · `use(plugin)` / `loadPlugin(name)` · `on/off(event, fn)` · `watch(resource, params, onData)` / `unwatch(id)`',
    '',
    '## Observability',
    '',
    '- `health()` / `healthOf(name)` · `rateLimits()` / `rateLimit(p)` · `circuits.status()` / `statusOf()` / `reset()` / `resetAll()` / `open()` / `close()` · `getMetrics()` / `metricsPrometheus()` · `providers.status()` / `statusOf()` / `reset()` · `toOpenAPI()` · `monitor` · `export`',
    '',
    '## Platform helpers (`helpers`, top-level exports)',
    '',
    '- `paginate` / `paginateStream` (`bemora/paginate`) · `gql` / `gqlTag` (`bemora/gql`) · `upload` (`bemora/upload`) · `batch` (`bemora/batch`) · `WebhookRouter` + `verifyWebhook` (`bemora/webhooks`) · `recordCost` / `costSnapshot` · `redact*` / `containsPII` · `createRedisAdapter*` (`bemora/redis`) · `signAwsRequest` / `hmacSign` / `hmacVerify`',
    '',
    '## Call shape',
    '',
    '```js',
    "import Bemora from 'bemora';",
    'const api = new Bemora();',
    '',
    "await api.weather.current({ city: 'Cairo' }); // keyed — needs BEMORA_WEATHER_KEY",
    'await api.space.issPosition(); // keyless — works out of the box',
    '```',
    '',
    '## Provider catalog',
    '',
    'Every method below is `api.<namespace>.<method>(params)`. Params column: `name*:type` where `*` = required.',
    '',
  ];

  for (const [cat, list] of byCategory()) {
    lines.push(`### ${cat}`, '');
    for (const [name, info] of list) {
      lines.push(`#### \`${name}\` — ${info.description}`);
      lines.push('');
      lines.push(`_${keyNote(info)}_`);
      lines.push('');
      lines.push('| Method | Params | Description |');
      lines.push('| --- | --- | --- |');
      for (const [method, desc] of Object.entries(info.methods)) {
        lines.push(`| \`${method}\` | ${fmtParams(SCHEMAS[name]?.[method])} | ${desc} |`);
      }
      lines.push('');
    }
  }

  lines.push('## Enterprise namespaces (not exposed as MCP tools)');
  lines.push('');
  lines.push('- `payments` (Stripe, PayPal) · `email` (SendGrid, SES, Resend) · `sms` (Twilio) · `auth` (Clerk, Auth0) · `jwt` · `storage` (S3, R2, GCS) · `vectordb` (Pinecone, Qdrant, Weaviate, pgvector) · `sentry` · `notifications` (OneSignal, Pusher, FCM) · `maps` (Google, Mapbox) · `searchEnt` (Algolia, Meilisearch) · `calendar` (Google, Calendly) · `captcha` (reCAPTCHA, hCaptcha, Turnstile) · `security` (HIBP, VirusTotal, Safe Browsing, urlscan) · `cloudflare`');
  lines.push('');

  return lines.join('\n');
}

// ── llms.txt ─────────────────────────────────────────────────────────────────
function renderLlmsTxt() {
  const lines = [
    `# bemora (v${pkg.version})`,
    '',
    '> Unified JavaScript/TypeScript API library and MCP server: one call shape `api.<namespace>.<method>(params)` across 100+ APIs (weather, finance, news, science, health, government, developer tooling, AI, and more), with retries, timeouts, circuit breakers, caching, rate-limit tracking, PII redaction and multi-tenant support. Most providers are keyless and work out of the box; keyed providers throw a coded ConfigurationError until their key is set.',
    '',
    `- ${totals.providers} providers · ${totals.methods} methods · ${totals.keyless} keyless (no API key).`,
    '- Install: `npm install bemora`. Node >= 18, ESM.',
    "- Use: `import Bemora from 'bemora'; const api = new Bemora(); await api.space.issPosition();`",
    '- MCP: `npx bemora-mcp` — every provider becomes an MCP tool named `<provider>_<method>`.',
    `- Full API reference: ${REPO}/blob/main/llms-full.txt`,
    `- Repository: ${REPO}`,
    '',
    '## Docs',
    '',
    `- [Getting started](${REPO}/blob/main/docs/getting-started.md)`,
    `- [Providers](${REPO}/blob/main/docs/providers.md)`,
    `- [API reference](${REPO}/blob/main/docs/api-reference.md) (generated)`,
    `- [MCP server](${REPO}/blob/main/docs/mcp.md)`,
    `- [Config & keys](${REPO}/blob/main/docs/configuration.md)`,
    `- [Errors](${REPO}/blob/main/docs/errors.md)`,
    '',
    '## Provider index',
    '',
  ];

  for (const [cat, list] of byCategory()) {
    lines.push(`### ${cat}`, '');
    for (const [name, info] of list) {
      const methods = Object.keys(info.methods).join(', ');
      lines.push(`- \`${name}\` (${keyNote(info)}): ${methods}`);
    }
    lines.push('');
  }

  lines.push('## Optional');
  lines.push('');
  lines.push(`- Full method signatures, params and examples: [llms-full.txt](${REPO}/blob/main/llms-full.txt)`);
  lines.push('');

  return lines.join('\n');
}

// ── llms-full.txt ────────────────────────────────────────────────────────────
function renderLlmsFull() {
  const lines = [
    `# bemora — full reference (v${pkg.version})`,
    '',
    '> Unified JavaScript/TypeScript API library and MCP server. One call shape: `await api.<namespace>.<method>(params)`. Auto-generated from the MCP catalog by `scripts/generate-docs.js`; do not edit by hand.',
    '',
    `Totals: ${totals.providers} providers · ${totals.methods} methods · ${totals.keyless} keyless.`,
    '',
    '## Install & setup',
    '',
    '```bash',
    'npm install bemora',
    '```',
    '',
    '```js',
    "import Bemora from 'bemora';",
    '',
    'const api = new Bemora({',
    '  weatherKey: process.env.BEMORA_WEATHER_KEY, // optional; env vars are read automatically',
    '});',
    '',
    '// Keyless provider — works immediately:',
    "const iss = await api.space.issPosition();",
    '',
    '// Keyed provider — reads BEMORA_WEATHER_KEY (or the key passed above):',
    "const weather = await api.weather.current({ city: 'Cairo' });",
    '```',
    '',
    'Keys are read from constructor options (e.g. `weatherKey`), from `BEMORA_<PROVIDER>_KEY` env vars, or set later with `api.setKey(name, value)`. Keyed providers throw a coded `ConfigurationError` when the key is missing.',
    '',
    'Every namespace is also an MCP tool: run `npx bemora-mcp` and call tool `<provider>_<method>` (e.g. `weather_current`, `space_issPosition`, `smart_weather`). Param names and types below are the tool input schemas.',
    '',
    '## Provider reference',
    '',
  ];

  for (const [cat, list] of byCategory()) {
    lines.push(`## ${cat}`, '');
    for (const [name, info] of list) {
      lines.push(`### ${name} — ${info.description}`);
      lines.push('');
      if (info.requiresKey) {
        lines.push(`- **Auth:** requires \`${info.keyName || 'API key'}\`${info.keyUrl ? ` — get one at ${info.keyUrl}` : ''}`);
      } else {
        lines.push('- **Auth:** none (keyless).');
      }
      if (info.category) lines.push(`- **Category:** ${info.category}`);
      lines.push('');
      for (const [method, desc] of Object.entries(info.methods)) {
        const schema = SCHEMAS[name]?.[method];
        lines.push(`- \`api.${name}.${method}(${fmtParams(schema)})\` — ${desc}`);
        const details = paramDetails(schema);
        if (details.length) lines.push(...details);
      }
      const firstMethod = Object.keys(info.methods)[0];
      lines.push('');
      lines.push('```js');
      lines.push(`await api.${name}.${firstMethod}(${exampleArgs(SCHEMAS[name]?.[firstMethod])});`);
      lines.push('```');
      lines.push('');
    }
  }

  lines.push('## Enterprise namespaces (available on the instance, not exposed as MCP tools)');
  lines.push('');
  lines.push('- `payments.stripe.*`, `payments.paypal.*` · `email.sendgrid|ses|resend.*` · `sms.twilio.*` · `auth.clerk|auth0.*` · `jwt.*` · `storage.s3|r2|gcs.*` · `vectordb.pinecone|qdrant|weaviate|pgvector.*` · `sentry.*` · `notifications.onesignal|pusher|fcm.*` · `maps.google|mapbox.*` · `searchEnt.algolia|meilisearch.*` · `calendar.google|calendly.*` · `captcha.recaptcha|hcaptcha|turnstile.*` · `security.hibp|virustotal|safebrowsing|urlscan.*` · `cloudflare.dns|r2|cache|workers.*`');
  lines.push('');

  return lines.join('\n');
}

const outputs = {
  'docs/api-reference.md': renderApiReference(),
  'llms.txt': renderLlmsTxt(),
  'llms-full.txt': renderLlmsFull(),
};

for (const [file, content] of Object.entries(outputs)) {
  fs.writeFileSync(path.join(root, file), content, 'utf8');
  console.log(`wrote ${file} (${content.split('\n').length} lines)`);
}

console.log(`totals: ${totals.providers} providers, ${totals.methods} methods, ${totals.keyless} keyless`);
